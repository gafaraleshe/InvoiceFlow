/**
 * Compose the full-schema SQL artifacts for a FRESH database.
 *
 *   server/db/schema.ts (via `drizzle-kit export`) + drizzle/pg/policies.sql
 *        ->  drizzle/pg/apply.sql        (paste into Supabase SQL Editor)
 *        ->  server/db/bootstrap-sql.ts  (served by /api/bootstrap-db)
 *
 * Why `drizzle-kit export` rather than concatenating drizzle/pg/0*.sql:
 *
 *   The numbered migrations are a *history*. Replaying them into one file is
 *   not the same as the current schema, and in this project it is actively
 *   broken — 0001 alters `memberships.user_id` to varchar while the foreign
 *   key to `users.id` still points at a uuid, so the sequence fails on a clean
 *   database. `export` emits the current end state of schema.ts, which is
 *   exactly what a fresh install needs and cannot drift from the source of
 *   truth.
 *
 * Both outputs were previously hand-maintained and had drifted: the `bookings`
 * table and its enum landed in 0001 but never reached either artifact, so any
 * database set up through the documented dashboard path was missing the whole
 * CRM.
 *
 * Run after every `pnpm db:pg:generate`:
 *
 *   pnpm gen:bootstrap
 */
import { execFileSync } from "node:child_process";
import { readFileSync, writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const ROOT = path.join(__dirname, "..");
const PG_DIR = path.join(ROOT, "drizzle", "pg");

const HEADER = `-- HermiteFlow — full schema + RLS for Supabase.
-- Paste this whole file into Supabase → SQL Editor → Run.
--
-- AUTO-GENERATED by scripts/gen-bootstrap-sql.mjs — do not edit by hand.
-- Source: server/db/schema.ts (via drizzle-kit export) + drizzle/pg/policies.sql
--
-- This is the FRESH-INSTALL script. To migrate an existing database, use the
-- numbered migrations instead: pnpm db:pg:migrate
`;

function exportSchema() {
  const out = execFileSync(
    "npx",
    ["drizzle-kit", "export", "--config", "drizzle.config.pg.ts", "--sql"],
    { cwd: ROOT, encoding: "utf8", maxBuffer: 32 * 1024 * 1024 }
  );
  // drizzle-kit prints its banner on stdout in some versions; keep only DDL.
  const start = out.search(/^(CREATE|ALTER|DROP)\b/m);
  if (start === -1) throw new Error("drizzle-kit export produced no DDL");
  return out.slice(start).trim();
}

const schemaSql = exportSchema();
const policies = readFileSync(path.join(PG_DIR, "policies.sql"), "utf8").trim();

const applySql = [
  HEADER,
  "-- ============ 1) SCHEMA ============",
  schemaSql,
  "",
  "-- ============ 2) ROW-LEVEL SECURITY ============",
  policies,
  "",
].join("\n");

writeFileSync(path.join(PG_DIR, "apply.sql"), applySql);
writeFileSync(
  path.join(ROOT, "server", "db", "bootstrap-sql.ts"),
  [
    "// AUTO-GENERATED by scripts/gen-bootstrap-sql.mjs — do not edit by hand.",
    "// Mirrors drizzle/pg/apply.sql so /api/bootstrap-db applies the same schema",
    "// as the Supabase SQL Editor path.",
    "",
    `export const BOOTSTRAP_SQL = ${JSON.stringify(applySql)};`,
    "",
  ].join("\n")
);

const tables = [...applySql.matchAll(/CREATE TABLE "(\w+)"/g)].map(m => m[1]);
console.log("wrote drizzle/pg/apply.sql and server/db/bootstrap-sql.ts");
console.log(`  tables (${tables.length}): ${tables.sort().join(", ")}`);
